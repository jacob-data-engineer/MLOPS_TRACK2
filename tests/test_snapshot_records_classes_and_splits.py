"""A snapshot records what the yaml declares, not just what it lists.

`train_images`, `val_images` and `classes` were filled ONLY from the
pinned file lists. A yaml that names FOLDERS -- which is every dataset
the Assemble card writes -- froze as:

    train_images 0    val_images 0    classes []

beside a manifest of 16,910 names. The class list is explicitly the
field that "makes an old run explicable after somebody reorders a
taxonomy", and it was the one most reliably absent.

Class names exist ONLY in `data.yaml`. A label line is
`2 0.51 0.22 0.26 0.08`, so scanning labels gives indices and counts and
never names -- if the freeze does not read them out of the yaml, nothing
anywhere remembers what index 2 meant.
"""
from __future__ import annotations

import pathlib
import sys

import pytest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src"))

from ppe_pipeline_api import dataset_snapshots as ds  # noqa: E402

ASSEMBLED = """\
# Generated by Assemble a dataset (yaml only, nothing copied).
path: s3://track2-s3/ds
train:
- images/train
val:
- images/val
names:
  0: helmet
  1: gloves
  2: person
"""

FILES = (["images/train/a%d.jpg" % i for i in range(4)]
         + ["labels/train/a%d.txt" % i for i in range(4)]
         + ["images/val/b%d.jpg" % i for i in range(2)]
         + ["labels/val/b%d.txt" % i for i in range(2)])


# --- the classes ------------------------------------------------------------------

def test_the_class_names_are_read_out_of_the_yaml():
    assert ds._yaml_names(ASSEMBLED) == {0: "helmet", 1: "gloves", 2: "person"}


def test_a_list_of_names_is_accepted_too():
    """The older Ultralytics spelling. Both are valid data.yaml."""
    assert ds._yaml_names("names: [helmet, gloves]") == {0: "helmet", 1: "gloves"}


def test_index_order_survives():
    """The order IS the meaning -- `2` in a label file is the third
    name, so a mapping that loses the index loses the dataset."""
    names = ds._yaml_names("names:\n  2: person\n  0: helmet\n  1: gloves\n")
    assert [names[i] for i in sorted(names)] == ["helmet", "gloves", "person"]


@pytest.mark.parametrize("text", ["", "names: [oops", "names: 7", "not: a mapping",
                                  "- just\n- a\n- list\n"])
def test_a_yaml_that_will_not_parse_does_not_stop_the_freeze(text):
    """A snapshot that refuses to be taken loses the record of a run
    that is about to happen anyway."""
    assert ds._yaml_names(text) == {}


# --- the split counts -------------------------------------------------------------

def test_a_folder_split_is_counted():
    assert ds._count_declared(ASSEMBLED, "train", FILES, "images") == 4
    assert ds._count_declared(ASSEMBLED, "val", FILES, "images") == 2


def test_labels_are_not_counted_as_images():
    """`train_images` means images."""
    assert ds._count_declared(ASSEMBLED, "train", FILES, "images") == 4


def test_a_single_folder_string_works_as_well_as_a_list():
    text = "train: images/train\nval: images/val\n"
    assert ds._count_declared(text, "train", FILES, "images") == 4


def test_several_folders_in_one_split_add_up():
    text = "train:\n- images/train\n- images/val\n"
    assert ds._count_declared(text, "train", FILES, "images") == 6


def test_a_path_list_is_left_to_the_lists():
    """A `.txt` split is already counted from the restored lists.
    Counting it here as well would double it."""
    text = "train: train.txt\nval: val.txt\n"
    assert ds._count_declared(text, "train", FILES, "images") == 0


def test_a_missing_split_is_zero_not_an_error():
    assert ds._count_declared("names: {0: a}", "val", FILES, "images") == 0


def test_a_folder_that_holds_nothing_counts_zero():
    text = "train: images/nowhere\n"
    assert ds._count_declared(text, "train", FILES, "images") == 0


def test_a_custom_images_subpath_is_honoured():
    files = ["pics/train/a.jpg", "anns/train/a.txt"]
    text = "train: pics/train\n"
    assert ds._count_declared(text, "train", files, "pics") == 1


def test_a_trailing_slash_does_not_lose_the_folder():
    text = "train: images/train/\n"
    assert ds._count_declared(text, "train", FILES, "images") == 4


# --- it is wired into the freeze ---------------------------------------------------

def test_the_freeze_uses_both_helpers():
    import inspect

    code = inspect.getsource(ds.create)
    assert "_yaml_names(yaml_text)" in code
    assert "_count_declared(" in code


def test_a_pinned_list_still_wins_over_the_folder_count():
    """When the yaml names a `.txt`, the restored lines ARE the answer;
    counting the folder as well would describe a different dataset."""
    import inspect

    code = inspect.getsource(ds.create)
    assert "listed_train or _count_declared(" in code
    assert "listed_val or _count_declared(" in code
